#!/usr/bin/env node
// Record the licence of every crate linked into the native binary, for THIRD_PARTY_NOTICES.md.
//   node scripts/crate-licenses.mjs           rewrite native/crate-licenses.json
//   node scripts/crate-licenses.mjs --check   fail when it does not list exactly native/Cargo.lock
// The list is committed so `npm run build` (which writes the notices) needs neither cargo nor a
// network. Licences come from `cargo metadata --offline` per release target (what cargo has
// cached), else from the crate's Cargo.toml in the local cargo registry; a crate whose licence
// could not be read is listed as such, never guessed.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { REPO_ROOT } from './lib/build.mjs';

const NATIVE = path.join(REPO_ROOT, 'native');
const OUT = path.join(NATIVE, 'crate-licenses.json');
const TARGETS = [
  'aarch64-apple-darwin',
  'x86_64-apple-darwin',
  'x86_64-unknown-linux-gnu',
  'aarch64-unknown-linux-gnu',
  'x86_64-pc-windows-msvc',
];

/** `[[package]]` entries of Cargo.lock: name, version, source. */
export function lockPackages(text) {
  return text
    .split(/\n\[\[package\]\]\n/)
    .slice(1)
    .map((block) => ({
      name: /^name = "(.*)"$/m.exec(block)?.[1],
      version: /^version = "(.*)"$/m.exec(block)?.[1],
      registry: /^source = "registry\+/m.test(block),
    }))
    .filter((p) => p.name && p.registry);
}

function metadata(target) {
  const r = spawnSync('cargo', ['metadata', '--format-version', '1', '--offline', '--filter-platform', target], {
    cwd: NATIVE,
    encoding: 'utf8',
    maxBuffer: 64 << 20,
  });
  return r.status === 0 ? JSON.parse(r.stdout) : null;
}

/** Crates reached from the dfw crate through normal (linked) dependencies, per target. */
function linked() {
  const found = new Map(); // "name version" -> { license, targets: Set, direct }
  const unread = [];
  for (const target of TARGETS) {
    const m = metadata(target);
    if (!m) {
      unread.push(target);
      continue;
    }
    const nodes = new Map(m.resolve.nodes.map((n) => [n.id, n]));
    const pkgs = new Map(m.packages.map((p) => [p.id, p]));
    const root = m.resolve.root;
    const direct = new Set(
      nodes
        .get(root)
        .deps.filter((d) => d.dep_kinds.some((k) => k.kind === null))
        .map((d) => d.pkg),
    );
    const seen = new Set();
    const walk = (id) => {
      for (const d of nodes.get(id).deps) {
        if (!d.dep_kinds.some((k) => k.kind === null) || seen.has(d.pkg)) continue;
        seen.add(d.pkg);
        walk(d.pkg);
      }
    };
    walk(root);
    for (const id of seen) {
      const p = pkgs.get(id);
      const key = `${p.name} ${p.version}`;
      const entry = found.get(key) || { license: p.license || null, targets: new Set(), direct: false };
      entry.targets.add(target);
      entry.direct ||= direct.has(id);
      found.set(key, entry);
    }
  }
  return { found, unread };
}

/** The `license = "..."` of a crate's Cargo.toml in the local registry, or null. */
function registryLicense(name, version) {
  const src = path.join(process.env.CARGO_HOME || path.join(os.homedir(), '.cargo'), 'registry', 'src');
  if (!fs.existsSync(src)) return null;
  for (const index of fs.readdirSync(src)) {
    const toml = path.join(src, index, `${name}-${version}`, 'Cargo.toml');
    if (fs.existsSync(toml)) return /^license\s*=\s*"(.*)"$/m.exec(fs.readFileSync(toml, 'utf8'))?.[1] ?? null;
  }
  return null;
}

function build() {
  const lock = lockPackages(fs.readFileSync(path.join(NATIVE, 'Cargo.lock'), 'utf8'));
  const { found, unread } = linked();
  const crates = [];
  for (const p of lock) {
    const key = `${p.name} ${p.version}`;
    const hit = found.get(key);
    // Not linked on a target cargo could resolve offline: linked only on an unread target, or
    // only a dev, build or other-platform dependency.
    const license = hit?.license ?? registryLicense(p.name, p.version);
    crates.push({
      name: p.name,
      version: p.version,
      license: license || 'not recorded (no licence field could be read)',
      direct: hit?.direct ?? false,
      linked: hit ? [...hit.targets].sort() : `none of ${TARGETS.filter((t) => !unread.includes(t)).join(', ')}`,
    });
  }
  return {
    $comment: 'Generated by node scripts/crate-licenses.mjs from native/Cargo.lock and cargo metadata. Do not edit.',
    unresolvedTargets: unread,
    crates,
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  if (process.argv.includes('--check')) {
    const lock = lockPackages(fs.readFileSync(path.join(NATIVE, 'Cargo.lock'), 'utf8'))
      .map((p) => `${p.name} ${p.version}`)
      .sort();
    const listed = JSON.parse(fs.readFileSync(OUT, 'utf8'))
      .crates.map((c) => `${c.name} ${c.version}`)
      .sort();
    if (JSON.stringify(lock) !== JSON.stringify(listed)) {
      console.error('native/crate-licenses.json does not match native/Cargo.lock: run node scripts/crate-licenses.mjs');
      process.exit(1);
    }
    console.log(`crate licences: ${listed.length} crates, as in Cargo.lock`);
  } else {
    const data = build();
    fs.writeFileSync(OUT, `${JSON.stringify(data, null, 2)}\n`);
    console.log(
      `wrote ${path.relative(REPO_ROOT, OUT)}: ${data.crates.length} crates${data.unresolvedTargets.length ? ` (not resolved offline: ${data.unresolvedTargets.join(', ')})` : ''}`,
    );
  }
}
