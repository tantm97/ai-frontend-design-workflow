#!/usr/bin/env node
// Record the licence of every crate linked into the native binary, for THIRD_PARTY_NOTICES.md.
//   node scripts/crate-licenses.mjs           rewrite native/crate-licenses.json
//   node scripts/crate-licenses.mjs --check   fail when it is not what this script writes now
// The list is committed so `npm run build` (which writes the notices) needs neither cargo nor a
// network. Licences and linked targets come from `cargo metadata --offline --filter-platform` for
// each release target (the targets of .github/workflows/release-binaries.yml), else from the
// crate's Cargo.toml in the local cargo registry, else from the committed list (a published crate
// version never changes). Cargo resolves a target offline only when the crates of that platform
// are downloaded: when a target or a licence cannot be read, nothing is written and the script
// says to run `cargo fetch --locked` (every crate of Cargo.lock, every platform). A licence is
// never guessed and never written as unknown.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { REPO_ROOT } from './lib/build.mjs';

const NATIVE = path.join(REPO_ROOT, 'native');
const OUT = path.join(NATIVE, 'crate-licenses.json');
const RELEASE_WORKFLOW = path.join(REPO_ROOT, '.github', 'workflows', 'release-binaries.yml');
const FETCH_HINT = 'run `cargo fetch --locked` in native/ (downloads every crate of Cargo.lock), then node scripts/crate-licenses.mjs';
const REGENERATE_HINT = 'run node scripts/crate-licenses.mjs, then npm run build';
const COMMENT = 'Generated by node scripts/crate-licenses.mjs from native/Cargo.lock and cargo metadata. Do not edit.';

/** `[[package]]` entries of Cargo.lock: name, version, source. */
export function lockPackages(text) {
  return text
    .split(/\n\[\[package\]\]\n/)
    .slice(1)
    .map((block) => ({
      name: /^name = "(.*)"$/m.exec(block)?.[1],
      version: /^version = "(.*)"$/m.exec(block)?.[1],
      registry: /^source = "registry\+/m.test(block),
    }))
    .filter((p) => p.name && p.registry);
}

/** The `target:` of each build in the release workflow's matrix, in its order. */
export function releaseTargets(workflowText) {
  return [...workflowText.matchAll(/^\s*- \{[^}]*\btarget: ([\w.-]+)\s*\}/gm)].map((m) => m[1]);
}

/**
 * What is wrong with a crate list, without cargo: crates other than those of Cargo.lock, a crate
 * with no licence, release targets other than the release workflow's.
 * @param {string} lockText native/Cargo.lock
 * @param {{ releaseTargets?: string[], crates?: { name: string, version: string, license?: string, linked?: unknown }[] }} data
 * @param {string[]} targets the release workflow's targets
 * @returns {string[]}
 */
export function listProblems(lockText, data, targets) {
  const problems = [];
  const lock = lockPackages(lockText)
    .map((p) => `${p.name} ${p.version}`)
    .sort();
  const crates = data.crates || [];
  const listed = crates.map((c) => `${c.name} ${c.version}`).sort();
  if (JSON.stringify(lock) !== JSON.stringify(listed))
    problems.push(`native/crate-licenses.json does not list exactly the crates of native/Cargo.lock: ${REGENERATE_HINT}`);
  if (JSON.stringify(data.releaseTargets) !== JSON.stringify(targets))
    problems.push(
      `native/crate-licenses.json lists the release targets ${JSON.stringify(data.releaseTargets)}, release-binaries.yml builds ${JSON.stringify(targets)}: ${REGENERATE_HINT}`,
    );
  const unread = crates.filter((c) => typeof c.license !== 'string' || !c.license || /not recorded/i.test(c.license));
  if (unread.length)
    problems.push(`native/crate-licenses.json has no licence for ${unread.map((c) => `${c.name} ${c.version}`).join(', ')}: ${FETCH_HINT}`);
  const badLinked = crates.filter((c) => !Array.isArray(c.linked) || c.linked.some((t) => !targets.includes(t)));
  if (badLinked.length)
    problems.push(
      `native/crate-licenses.json: "linked" is not a list of release targets for ${badLinked.map((c) => c.name).join(', ')}: ${REGENERATE_HINT}`,
    );
  return problems;
}

function metadata(target) {
  const r = spawnSync('cargo', ['metadata', '--format-version', '1', '--offline', '--filter-platform', target], {
    cwd: NATIVE,
    encoding: 'utf8',
    maxBuffer: 64 << 20,
  });
  return r.status === 0 ? JSON.parse(r.stdout) : null;
}

/** Crates reached from the dfw crate through normal (linked) dependencies, per target. */
function linked(targets) {
  const found = new Map(); // "name version" -> { license, targets: Set, direct }
  const unread = [];
  for (const target of targets) {
    const m = metadata(target);
    if (!m) {
      unread.push(target);
      continue;
    }
    const nodes = new Map(m.resolve.nodes.map((n) => [n.id, n]));
    const pkgs = new Map(m.packages.map((p) => [p.id, p]));
    const root = m.resolve.root;
    const direct = new Set(
      nodes
        .get(root)
        .deps.filter((d) => d.dep_kinds.some((k) => k.kind === null))
        .map((d) => d.pkg),
    );
    const seen = new Set();
    const walk = (id) => {
      for (const d of nodes.get(id).deps) {
        if (!d.dep_kinds.some((k) => k.kind === null) || seen.has(d.pkg)) continue;
        seen.add(d.pkg);
        walk(d.pkg);
      }
    };
    walk(root);
    for (const id of seen) {
      const p = pkgs.get(id);
      const key = `${p.name} ${p.version}`;
      const entry = found.get(key) || { license: p.license || null, targets: new Set(), direct: false };
      entry.targets.add(target);
      entry.direct ||= direct.has(id);
      found.set(key, entry);
    }
  }
  return { found, unread };
}

/** The `license = "..."` of a crate's Cargo.toml in the local registry, or null. */
function registryLicense(name, version) {
  const src = path.join(process.env.CARGO_HOME || path.join(os.homedir(), '.cargo'), 'registry', 'src');
  if (!fs.existsSync(src)) return null;
  for (const index of fs.readdirSync(src)) {
    const toml = path.join(src, index, `${name}-${version}`, 'Cargo.toml');
    if (fs.existsSync(toml)) return /^license\s*=\s*"(.*)"$/m.exec(fs.readFileSync(toml, 'utf8'))?.[1] ?? null;
  }
  return null;
}

/** Licences of the committed list, by "name version" (a published crate version never changes). */
function committedLicenses() {
  const out = new Map();
  if (!fs.existsSync(OUT)) return out;
  for (const c of JSON.parse(fs.readFileSync(OUT, 'utf8')).crates || [])
    if (typeof c.license === 'string' && c.license && !/not recorded/i.test(c.license)) out.set(`${c.name} ${c.version}`, c.license);
  return out;
}

/** The crate list as it should be now, or the reasons it cannot be read offline. */
function build(targets) {
  const lock = lockPackages(fs.readFileSync(path.join(NATIVE, 'Cargo.lock'), 'utf8'));
  const { found, unread } = linked(targets);
  const committed = committedLicenses();
  const crates = [];
  const missing = [];
  for (const p of lock) {
    const key = `${p.name} ${p.version}`;
    const hit = found.get(key);
    // Not in `found`: a dev, build or other-platform dependency, linked on no release target.
    const license = hit?.license ?? registryLicense(p.name, p.version) ?? committed.get(key) ?? null;
    if (!license) missing.push(key);
    crates.push({ name: p.name, version: p.version, license, direct: hit?.direct ?? false, linked: hit ? [...hit.targets].sort() : [] });
  }
  const problems = [];
  if (unread.length) problems.push(`cargo could not resolve ${unread.join(', ')} offline`);
  if (missing.length) problems.push(`no licence could be read for ${missing.join(', ')}`);
  return { problems, data: { $comment: COMMENT, releaseTargets: targets, crates } };
}

const serialize = (data) => `${JSON.stringify(data, null, 2)}\n`;

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  const targets = releaseTargets(fs.readFileSync(RELEASE_WORKFLOW, 'utf8'));
  if (!targets.length) {
    console.error(`no build targets found in ${path.relative(REPO_ROOT, RELEASE_WORKFLOW)} (matrix lines "- { ..., target: <triple> }")`);
    process.exit(1);
  }
  const { problems, data } = build(targets);
  if (problems.length) {
    console.error(
      `native/crate-licenses.json ${process.argv.includes('--check') ? 'not checked' : 'not written'}: ${problems.join('; ')}: ${FETCH_HINT}`,
    );
    process.exit(1);
  }
  if (process.argv.includes('--check')) {
    const text = fs.readFileSync(OUT, 'utf8');
    const listed = listProblems(fs.readFileSync(path.join(NATIVE, 'Cargo.lock'), 'utf8'), JSON.parse(text), targets);
    if (listed.length || text !== serialize(data)) {
      console.error(
        listed.length ? listed.join('\n') : `native/crate-licenses.json is stale (cargo metadata says otherwise): ${REGENERATE_HINT}`,
      );
      process.exit(1);
    }
    console.log(`crate licences: ${data.crates.length} crates, as cargo metadata reads them for ${targets.join(', ')}`);
  } else {
    fs.writeFileSync(OUT, serialize(data));
    console.log(`wrote ${path.relative(REPO_ROOT, OUT)}: ${data.crates.length} crates, ${targets.length} release targets`);
  }
}
